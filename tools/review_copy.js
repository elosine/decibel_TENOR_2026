#!/usr/bin/env node
// review_copy.js — THE PERFORMANCE INSTRUCTIONS' REVIEW COPY (TENOR 2027, double-blind; running order step 4, 2026-10-24): the page
// docs/notation_instructions/index.html with the composer's name line and his YouTube demo line taken out, and without the edit
// switch (a Save from the copy would write the page) → docs/notation_instructions/review.html, in the same folder so its images
// resolve the same. GENERATED: never edited by hand — run again after any change to the page.
//   node tools/review_copy.js
'use strict';
const fs = require('fs'), path = require('path');
const DIR = path.join(__dirname, '..', 'docs', 'notation_instructions');
let s = fs.readFileSync(path.join(DIR, 'index.html'), 'utf8');
const cuts = [
  [/^[ \t]*<script src="edit\.js"[^>]*><\/script>\r?\n/m, 'the edit switch'],
  [/^[ \t]*<div class="piece-by">[^<]*<\/div>\r?\n/m, 'the name line'],
  [/^[ \t]*<p class="demo-link">[\s\S]*?<\/p>\r?\n/m, 'the demo line (his YouTube channel)'],
];
for (const [re, what] of cuts) {
  if ((s.match(new RegExp(re.source, 'gm')) || []).length !== 1) { console.error('review_copy: ' + what + ' not found exactly once — NOTHING WRITTEN'); process.exit(2); }
  s = s.replace(re, '');
}
s = s.replace(/<!--[\s\S]*?-->[ \t]*(\r?\n)?/g, '');     // the page's working comments carry the record (and his links): none in the copy
if (/Justin|Yang|youtu|elosine/i.test(s)) { console.error('review_copy: a name or a YouTube link is still on the page — NOTHING WRITTEN'); process.exit(3); }
s = s.replace(/<head>/, '<head>\n    <!-- GENERATED by tools/review_copy.js from index.html — the review copy (no name). Do not edit: change index.html, then run it again. -->');
fs.writeFileSync(path.join(DIR, 'review.html'), s);
console.log('wrote docs/notation_instructions/review.html — ' + cuts.map((c) => c[1]).join(' · ') + ' taken out');
